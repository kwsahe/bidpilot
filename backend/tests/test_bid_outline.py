def test_번호_붙은_옛_분석_이름도_찾고_제안요청서를_발췌에_쓴다(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    # 1718593 — 옛 분석은 「2_2_과업지시서…」처럼 캐시 번호까지 적었고, 같은 폴더에 「3_3_제안요청서…」가 따로 있다
    monkeypatch.setattr(attachment_service, "CACHE_DIR", tmp_path / "real_rfp")
    for index, name in ((2, "2_과업지시서_시험.hwp"), (3, "3_제안요청서_시험.hwp")):
        path = attachment_service.cache_path(PID, index, name)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b"\xd0\xcf\x11\xe0" + name.encode())
    monkeypatch.setattr(document_extractor, "extract_document", lambda path, file_name=None, **_: document_extractor.ExtractedDocument(
        file_name=file_name, doc_format="hwp", pages=[document_extractor.DocumentPage(page=1, text=f"본문 {file_name}")]))
    monkeypatch.setattr(rfp_parser, "load_generated", lambda pid: SimpleNamespace(
        document_role="rfp", document="2_2_과업지시서_시험.hwp", requirement_set_hash="h"))
    assert bid.cached_source(PID, "2_2_과업지시서_시험.hwp") is not None  # 번호를 떼고 한 번 더
    source = bid.load_source(PID, SimpleNamespace(notice=SimpleNamespace(title="공고", agency="기관", raw_data={})))
    assert [d["name"] for d in source["docs"]] == ["2_과업지시서_시험.hwp", "3_제안요청서_시험.hwp"]
    assert source["text"] == "본문 3_제안요청서_시험.hwp"  # 분석이 과업지시서여도 제안요청서가 있으면 발췌는 제안요청서


