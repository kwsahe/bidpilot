def test_미리_보기_꼴과_분량_줄이기(monkeypatch: pytest.MonkeyPatch) -> None:
    text = DOC_TOC + "\n본문은 30페이지 이내로 작성\n□ 제안서 목차 및 작성 방법\nⅠ. 제안개요\n1. 제안 목적\nⅡ. 제안사 일반\n1. 일반현황\nⅢ. 사업수행부문\n1. 개요\n□ 입찰 방법"
    monkeypatch.setattr(bid, "load_documents", lambda pid: (None, [_doc(text, name="사전규격 규격서 1(R26BD0)", role="spec")]))
    preview = bid.outline_preview(PID, None)
    assert set(preview) == {"procurement_id", "outline_source", "outline", "outline_where", "outline_found_at", "outline_rejected",
                            "evaluation", "format", "documents", "warnings", "renumbered"}  # renumbered — 고쳐 붙인 대항목 번호(2.8.0 B5)
    assert preview["renumbered"] == []
    assert preview["outline_source"] == "rfp" and preview["outline"][0] == {"no": "Ⅰ", "title": "제안개요", "items": [{"no": "1", "title": "제안 목적"}]}
    assert preview["outline_rejected"] and set(preview["outline_rejected"][0]) == {"head", "page", "reason"}
    assert preview["documents"] == [{"name": "사전규격 규격서 1(R26BD0)", "role": "spec", "pages": 1}]
    # 목차 · 평가표를 못 읽은 것은 화면 줄이 알린다 — 경고에는 사전규격 원문만(중복 없음)
    assert preview["warnings"] == ["원문이 사전규격 규격서입니다 — 본공고 제안요청서와 다를 수 있습니다"]
    assert preview["outline_found_at"] is None  # 목차를 읽었으면 「못 읽은 곳」은 비운다(unread 때만)
    # 머리는 찾았는데 못 읽은 원문 — 표준 목차 · 머리를 찾은 곳이 실린다
    monkeypatch.setattr(bid, "load_documents", lambda pid: (None, [_doc("본문\n□ 제안서 목차 및 작성 방법\n별도 서식 참조\n□ 입찰 방법")]))
    unread = bid.outline_preview(PID, None)
    assert unread["outline_source"] == "unread" and unread["warnings"] == []
    assert unread["outline_found_at"] == {"document": "제안요청서.hwp", "page": 1, "head": "□ 제안서 목차 및 작성 방법"}
    assert preview["format"]["page_limit"] == 30
    # 30쪽 · 소항목 3개 → 30 × 1,100 × 75% ÷ 3 = 8,250 → 지금 값보다 크면 지금 값 · 상한이 작으면 줄인다(최소 350)
    units = [{"key": "a", "target": "task"}, {"key": "b", "target": "overview"}]
    assert bid.unit_targets(units, None) == {"a": 3000, "b": 700}
    assert bid.unit_targets(units, 2) == {"a": 825, "b": 700}
    assert bid.unit_targets(units * 10, 1) == {"a": 350, "b": 350}
