def _paged(text: str, name: str = "2. 제안요청서.hwp", role: str = "rfp") -> dict:
    parts = re.split(r"^=== (\d+)쪽 ===$", text, flags=re.M)
    pages = [(int(parts[i]), parts[i + 1]) for i in range(1, len(parts), 2)] or [(1, text)]
    return {"name": name, "role": role, "pages": pages, "text": "\n".join(body for _, body in pages)}


