def excerpt(*segments: list[str]) -> str:
    """발췌를 빈 줄로 이어 붙인다 — 빈 줄은 쪽 바닥줄처럼 「표가 끝났다」로 읽힌다."""
    return "\n\n".join("\n".join(seg) for seg in segments)


