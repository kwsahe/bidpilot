"""회사가 «신청자»가 될 수 없는 공고를 가려낸다 (ISSUE-005 · TASK-008).

## 왜 필요한가

2026-09-16 실데이터에서 통합 목록 1위(76점 · 「우선 검토」)가
「2026년 공예 온라인 유통 및 AI 활용 역량 강화 교육프로그램 **교육생 모집** 공고」였다.
본문은 「만 19세 이상 공예작가·유통사업자를 모집」 — 개인이 수강 신청하는 안내문이고,
샘플에듀가 신청할 수 있는 사업이 아니다. 그런데 「AI」「교육」「역량 강화」가 모두 있어
사업영역 1.0 을 받았다.

「반려동물 창업 아이디어 **경진대회 참가자 모집**」(55점), 「전주국제발효식품엑스포
**참가기업**」(54점)도 같은 자리에 섞여 있었다.

1위가 엉뚱하면 목록 전체의 신뢰가 무너진다. 담당자는 GPT 로 손수 하던 「무관 공고 빼기」를
이 화면에서 또 해야 한다.

## 어떻게 판정하는가

키워드 하나로 자르지 않는다. 「교육생」은 샘플에듀가 **운영하는** 교육의 대상이기도 하다
(「교육생 200명 대상 교육 운영」은 우리 일이다). 그래서 순서대로 본다.

1. 회사가 **수행자**로 들어갈 신호(운영·용역·위탁…)가 있는가 (`_EXECUTION_RE`) → 우리 일이다
2. **기업**을 모집하는가 (`_COMPANY_RE`) → 회사가 신청 주체다
3. **사람**을 모집하는가 (`_INDIVIDUAL_RE`) → 회사가 신청 주체가 아니다
4. **참가·출품** 기회인가 (`_PARTICIPATION_RE`) → 신청 주체가 될 수는 있어도 수행할 사업이 아니다

2번과 3번을 가른 것이 15차다 (ISSUE-125). 예전에는 「참가기업」·「참여기업」이 3번 안에
들어 있어 **기업 모집 공고에도 개인 안내가 붙었다.**

## 무엇을 하지 않는가

**지우지 않는다.** 점수를 낮추고 사유를 붙일 뿐이다. 규칙이 틀렸을 때 담당자가
목록에서 찾을 수조차 없게 되는 쪽이 더 나쁘다 (CLAUDE.md 11 — 모호하면 CHECK).
"""

from __future__ import annotations

import re
from typing import Final

#: 「누구를 모집하는가」가 **사람**인 신호 (15차에 둘로 갈랐다 · ISSUE-125 · prompt_05 §4-E-1).
#:
#: 예전에는 여기 「참가기업」·「참여기업」이 함께 들어 있었다. 그래서 이 규칙이 **기업을
#: 모집하는 공고에도 붙었다** — 기업마당 1,620건 중 「참여기업 모집」이 들어간 공고가 수백
#: 건이라, 12차·13차는 「건드리면 그만큼이 한꺼번에 낮아진다」며 손대기를 미뤘다.
#:
#: 사람과 기업은 서로 다른 신호이고, 섞여 있으면 어느 쪽도 제대로 쓸 수 없다. 「모집」 한
#: 낱말로는 부족한 것과 같은 이유다 — 「용역업체 모집」도 모집이다.
_INDIVIDUAL_RE: Final[re.Pattern[str]] = re.compile(
    r"(?:교육생|수강생|참가자|참여자|참가\s*팀|참가\s*자|입교생|연수생|훈련생|예비\s*창업자"
    r"|작가|청년|장애인|주민|학생|일반인|개인|1\s*인)\s*(?:을|를|모집|선발|공모|추가\s*모집)"
    r"|(?:모집|선발|공모)\s*(?:대상|인원)\s*[:：]?\s*(?:만?\s*\d+\s*세|개인|일반인|청년|학생)"
    r"|수강\s*신청|참가\s*신청\s*안내|참가자\s*모집|교육생\s*모집|수강생\s*모집"
)

#: 「누구를 모집하는가」가 **기업**인 신호. 이것이 있으면 회사가 신청 주체가 될 수 있다.
#:
#: 이 신호는 위 규칙보다 **먼저** 본다. 「참여기업 모집」 공고에 「청년을 채용하는」 같은
#: 문구가 섞여 있어도, 신청서를 내는 것은 기업이다 (예: 미래내일 일경험 — 참여기업이 신청하고
#: 청년이 인턴으로 온다. 기준 답안 A3 이 그 건이고 상위 5 안에 있어야 한다).
_COMPANY_RE: Final[re.Pattern[str]] = re.compile(
    r"참여\s*기업|참가\s*기업|수요\s*기업|공급\s*기업|참여\s*업체|참여\s*기관|모집\s*기업"
)

#: 「회사가 수행자로 들어간다」는 신호. 이게 있으면 위 문구가 있어도 제외하지 않는다.
_EXECUTION_RE: Final[re.Pattern[str]] = re.compile(
    r"용역|위탁|운영\s*기관|수행\s*기관|운영\s*대행|위수탁|제안\s*요청|입찰|낙찰|계약\s*상대자"
    r"|교육\s*운영|운영\s*용역|주관\s*기관\s*모집|수행\s*기업\s*모집|운영사\s*모집"
)

#: 「참가할 기회」이지 「수행할 사업」이 아닌 것들. 회사가 신청 주체가 되더라도
#: 샘플에듀가 파는 것(교육·컨설팅 수행)과 성격이 다르다.
#:
#: **「참가기업 모집」은 15차에 뺐다** (ISSUE-125 · prompt_05 §4-E-1). 그것은 「무엇을 하는
#: 자리인가」가 아니라 「누가 신청하는가」를 말하는 문구라 이 축에 있을 것이 아니었다 —
#: 이제 `_COMPANY_RE` 가 본다. 여기 남겨 두면 「참가기업 모집」이라는 말만으로 105건이
#: 「수행할 사업이 아니다」로 깎였다(실측). 행사 자체를 가리키는 말(엑스포·박람회·경진대회·
#: 공모전·부스)만 남긴다 — 「전주국제발효식품엑스포 참가기업」은 「엑스포」로 그대로 걸린다.
_PARTICIPATION_RE: Final[re.Pattern[str]] = re.compile(
    r"경진\s*대회|공모전|해커톤|아이디어\s*경진|경연\s*대회"
    r"|엑스포|박람회|전시회\s*참가|부스\s*참가"
)


#: 「개인을 모집한다」 안내. 어느 쪽인지 **이름으로** 묻고 싶을 때 쓴다 (ISSUE-125).
INDIVIDUAL = "individual"
#: 「참가·출품 기회다」 안내.
PARTICIPATION = "participation"


def audience_kind(text: str) -> str | None:
    """안내가 붙는다면 **어느 쪽인지**. 아니면 None.

    문장으로 되묻지 않게 이름을 따로 돌려준다 — 점수 규칙(전략적 가치)과 「이번 주 할 일」이
    둘을 다르게 다루기 때문이다 (prompt_05 §4-E-1).
    """
    if not text:
        return None
    if _EXECUTION_RE.search(text):
        return None
    if not _COMPANY_RE.search(text) and _INDIVIDUAL_RE.search(text):
        return INDIVIDUAL
    if _PARTICIPATION_RE.search(text):
        return PARTICIPATION
    return None


def audience_note(text: str) -> str | None:
    """회사가 신청자가 될 수 없어 보이면 사유 문장, 아니면 None.

    돌려주는 문장은 그대로 화면에 나간다 — 담당자가 읽고 스스로 판단할 수 있게
    «무엇을 보고 그렇게 판정했는지»를 적는다.
    """
    if not text:
        return None
    if _EXECUTION_RE.search(text):
        return None
    # **기업을 모집하는 공고면 개인 안내를 붙이지 않는다** (ISSUE-125 · prompt_05 §4-E-1).
    #
    # 참가·출품 판정(아래)까지 건너뛰지는 않는다. 그쪽은 「누가 신청하는가」가 아니라
    # 「무엇을 하는 자리인가」를 보는 **다른 축**이고, 엑스포·경진대회는 기업이 신청해도
    # 샘플에듀가 파는 것(교육·컨설팅 수행)과 성격이 다르다 — 「전주국제발효식품엑스포
    # 참가기업」(54점)이 ISSUE-005 에서 고친 바로 그 건이다. 여기서 함께 풀면 그 고침이
    # 되돌아간다.
    if not _COMPANY_RE.search(text) and _INDIVIDUAL_RE.search(text):
        return "개인·수강생을 모집하는 안내입니다. 회사가 신청하는 사업인지 원문에서 확인하세요."
    if _PARTICIPATION_RE.search(text):
        return "참가·출품 기회이고 수행할 사업이 아닙니다. 참여 목적이 맞는지 원문에서 확인하세요."
    return None
